/*jQuery anonymous function calls*/
(function($) {
$(function() {
if( $('.magnific-1').length ){
	$('.magnific-1').magnificPopup({
	  delegate: 'a', // child items selector, by clicking on it popup will open
	  type: 'image',
	  gallery: {
	  	enabled:true
	  }
	  // other options
	});
}
});
})(jQuery);

